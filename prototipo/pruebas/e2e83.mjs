// Comprobaciones de la capa R8.3 (planes preventivos por combustible y uso).
// Uso: node pruebas/e2e83.mjs <ruta absoluta de R_Motriz_R8.3.html> [carpeta de capturas]
import { chromium } from 'playwright';
const F = 'file://' + process.argv[2] + '#sinlogin', dir = process.argv[3] || '.';
const b = await chromium.launch(process.env.PW_CHROMIUM ? { executablePath: process.env.PW_CHROMIUM } : {});
const p = await b.newPage({ viewport: { width: 1366, height: 900 } }); p.setDefaultTimeout(5000);
const errs = []; p.on('pageerror', e => errs.push('pageerror: ' + e.message)); p.on('console', m => { if (m.type() === 'error') errs.push('console: ' + m.text()) });
let ok = 0, mal = 0; const ck = (n, c, x = '') => { c ? ok++ : mal++; console.log((c ? 'OK   ' : 'FALLA') + ' ' + n + (x !== '' ? ' → ' + x : '')) };
await p.goto(F); await p.waitForTimeout(400);
await p.evaluate(() => go('planes')); await p.waitForTimeout(150);
const total = async () => +(await p.textContent('.r83-total')).match(/(\d+) servicios/)[1];
const filas = () => p.locator('.r83-tabla tbody tr:not(.r83-no)').count();
ck('título', (await p.textContent('#view h1')) === 'Planes preventivos');
ck('11 categorías', await p.locator('.r83-cat').count() === 11, await p.locator('.r83-cat').count());
const gasTodo = await total();
ck('gasolina particular sin filtros = 51 líneas', gasTodo === 51, gasTodo);
const visita = async km => { await p.evaluate(k => r83Set('visita', k), km); await p.waitForTimeout(60); return total() };
ck('particular 5.000 km = express de 5', await visita(5000) === 5, await total());
ck('particular 10.000 km = express de 5', await visita(10000) === 5, await total());
const p15 = await visita(15000);
ck('particular 15.000 km = menor + afinamiento (14 + 6)', p15 === 20, p15);
ck('etiqueta de 15.000 km', (await p.textContent('.r83-vis.on span')) === 'Menor + afinamiento');
ck('etiqueta de 30.000 km', (await visita(30000), await p.textContent('.r83-vis.on span')) === 'Mayor + afinamiento');
ck('mayor particular trae al menos las 26 fijas', await total() >= 26 + 6, await total());
await p.evaluate(() => r83Set('uso', 'S')); await p.waitForTimeout(60);
ck('severo 5.000 km = express de 5', await visita(5000) === 5, await total());
ck('severo 10.000 km = menor de 14', await visita(10000) === 14, await total());
ck('severo 20.000 km = menor + afinamiento', (await visita(20000), await p.textContent('.r83-vis.on span')) === 'Menor + afinamiento', await total());
ck('severo 15.000 km = express', (await visita(15000), await p.textContent('.r83-vis.on span')) === 'Express', await total());
await p.evaluate(() => { r83Set('visita', 0); r83Set('uso', 'P'); r83Set('plan', 'DIE') }); await p.waitForTimeout(60);
ck('diésel no muestra bujías', !(await p.locator('.r83-tabla tbody tr:not(.r83-no)').allTextContents()).some(t => /bujías/i.test(t)));
ck('diésel muestra opacidad', (await p.locator('.r83-tabla tbody tr:not(.r83-no)').allTextContents()).some(t => /opacidad/i.test(t)));
await p.evaluate(() => { r83Set('plan', 'GAS'); r83Set('dist', 'cadena') }); await p.waitForTimeout(60);
ck('cadena oculta la correa de distribución', !(await p.locator('.r83-tabla tbody tr:not(.r83-no)').allTextContents()).some(t => /correa de distribución/i.test(t)));
const antes = await filas();
await p.locator('.r83-cat').nth(7).locator('.r83-ver').click(); await p.waitForTimeout(60);
ck('«Ver todos» muestra atenuadas las que no corresponden', await p.locator('.r83-cat').nth(7).locator('tr.r83-no').count() === 2, await p.locator('.r83-cat').nth(7).locator('tr.r83-no').count());
ck('«Ver todos» no cambia las que sí corresponden', await filas() === antes);
const t0 = await total();
await p.locator('.r83-cat').nth(7).locator('tr.r83-no input').first().check(); await p.waitForTimeout(80);
ck('marcar una línea la agrega al plan', await total() === t0 + 1, await total());
await p.evaluate(() => r83Plegar(true)); await p.waitForTimeout(60);
ck('plegar todo oculta las tablas', await p.locator('.r83-cat .r83-tabla').count() === 0);
await p.locator('.r83-plega').first().click(); await p.waitForTimeout(60);
ck('una categoría se despliega sola', await p.locator('.r83-cat .r83-tabla').count() === 1);
await p.evaluate(() => { db.r83.extra = {}; R83.todos = new Set(); r83Plegar(false); r83Set('dist', ''); r83Set('visita', 5000) }); await p.waitForTimeout(80);
const fondo = await p.evaluate(() => Math.round(document.querySelector('.r83-cats').getBoundingClientRect().bottom));
ck('la visita express cabe en una pantalla de 900 px', fondo <= 900, fondo);
await p.screenshot({ path: dir + '/r83_express.png' });
await p.evaluate(() => r83Set('visita', 15000)); await p.waitForTimeout(80); await p.screenshot({ path: dir + '/r83_menor_afinamiento.png', fullPage: true });
await p.evaluate(() => { r83Set('visita', 0); r83VerTodo(true) }); await p.waitForTimeout(80); await p.screenshot({ path: dir + '/r83_ver_todos.png', fullPage: true });
await p.evaluate(() => { r83VerTodo(false); r83Set('dist', 'cadena'); r83Set('caja', 'mecanica'); r83Set('trac', '4x2') }); await p.waitForTimeout(60);
ck('código del plan', (await p.textContent('.r83-cod')) === 'PMP-G-CA-ME-2-N', await p.textContent('.r83-cod'));
ck('caja mecánica oculta el filtro de caja', !(await p.locator('.r83-tabla tbody tr:not(.r83-no)').allTextContents()).some(t => /filtro de caja/i.test(t)));
ck('encendido agrupa el afinamiento', (await p.locator('.r83-cat').nth(2).textContent()).includes('Sistema de encendido (afinamiento de motor)') && (await p.locator('.r83-cat').nth(2).textContent()).includes('Limpieza de inyectores'));
await p.screenshot({ path: dir + '/r83_codigo.png', fullPage: true });
await p.evaluate(() => { r83Set('dist', ''); r83Set('caja', ''); r83Set('trac', '') });
ck('sin desborde horizontal', await p.evaluate(() => document.documentElement.scrollWidth - innerWidth) <= 0);
await p.evaluate(() => go('timeline')); await p.waitForTimeout(150);
ck('la línea temporal sigue abriendo', !!(await p.textContent('#view h1')));
ck('sin errores de consola', errs.length === 0, errs.join(' | '));
console.log(`\n${ok} correctas, ${mal} fallas`); await b.close(); process.exit(mal ? 1 : 0);
